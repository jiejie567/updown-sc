#!/usr/bin/env python3
"""Paper figure for RTK-SLAM Construction Hall cross-sequence retrieval.

Figure contract
---------------
Core claim:
    UpDown-SC improves cross-traversal place-retrieval recall over established
    single-scan descriptors under identical experiment-only 2 m keyframes.
Evidence:
    Panel a verifies the two traversals and spatial coverage in the map frame.
    Panel b reports Recall@1/5/10 and separates single-scan methods from
    causal accumulated-input methods.
Archetype:
    Asymmetric mixed-modality figure (trajectory context + quantitative hero).
Source data:
    recall_summary.csv, scans.pcd, and aligned TUM trajectories generated by
    the Construction Hall experiment scripts; no simulated values.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np


WIDTH_MM = 183.0
HEIGHT_MM = 92.0
MM_PER_INCH = 25.4

mpl.rcParams.update(
    {
        "font.family": "sans-serif",
        "font.sans-serif": ["Arial", "Helvetica", "DejaVu Sans"],
        "font.size": 7.0,
        "axes.labelsize": 7.0,
        "axes.titlesize": 7.5,
        "xtick.labelsize": 6.5,
        "ytick.labelsize": 6.5,
        "legend.fontsize": 6.5,
        "svg.fonttype": "none",
        "pdf.fonttype": 42,
        "axes.linewidth": 0.6,
        "xtick.major.width": 0.6,
        "ytick.major.width": 0.6,
    }
)


def read_binary_pcd_xy(path: Path) -> np.ndarray:
    with path.open("rb") as stream:
        header: dict[str, list[str]] = {}
        while True:
            line = stream.readline()
            if not line:
                raise RuntimeError(f"Missing DATA line in {path}")
            text = line.decode("ascii").strip()
            if not text or text.startswith("#"):
                continue
            key, *values = text.split()
            header[key.upper()] = values
            if key.upper() == "DATA":
                break
        if header["DATA"][0].lower() != "binary":
            raise RuntimeError(f"Expected binary PCD: {path}")
        fields = header["FIELDS"]
        sizes = [int(value) for value in header["SIZE"]]
        types = header["TYPE"]
        counts = [int(value) for value in header.get("COUNT", ["1"] * len(fields))]
        dtype_fields = []
        for field, size, field_type, count in zip(fields, sizes, types, counts):
            if field_type == "F" and size == 4:
                dtype = "<f4"
            elif field_type == "F" and size == 8:
                dtype = "<f8"
            elif field_type == "U" and size == 4:
                dtype = "<u4"
            else:
                raise RuntimeError(
                    f"Unsupported PCD field {field}: type={field_type} size={size}"
                )
            dtype_fields.append((field, dtype, (count,)) if count > 1 else (field, dtype))
        points = np.fromfile(
            stream,
            dtype=np.dtype(dtype_fields),
            count=int(header["POINTS"][0]),
        )
    xy = np.column_stack((points["x"], points["y"])).astype(np.float64)
    return xy[np.isfinite(xy).all(axis=1)]


def read_summary(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def load_tum_xy(path: Path) -> np.ndarray:
    values = np.loadtxt(path, dtype=np.float64)
    if values.ndim == 1:
        values = values[None, :]
    return values[:, 1:3]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--experiment-root", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    root = args.experiment_root
    output_dir = args.output_dir or root / "figures"
    output_dir.mkdir(parents=True, exist_ok=True)

    summary = read_summary(root / "results/recall_summary.csv")
    map_xy = read_binary_pcd_xy(root / "seq1/scans.pcd")
    map_path = load_tum_xy(root / "seq1/session/optimized_poses_tum.txt")
    query_truth = load_tum_xy(root / "derived/seq2_truth_in_seq1_map_tum.txt")

    fig = plt.figure(
        figsize=(WIDTH_MM / MM_PER_INCH, HEIGHT_MM / MM_PER_INCH),
        constrained_layout=False,
    )
    grid = fig.add_gridspec(
        1,
        2,
        width_ratios=[0.96, 1.25],
        left=0.055,
        right=0.985,
        bottom=0.13,
        top=0.95,
        wspace=0.30,
    )
    ax_map = fig.add_subplot(grid[0, 0])
    ax_bar = fig.add_subplot(grid[0, 1])

    # Panel a: real map and the two translation-only 2 m keyframe tracks.
    stride = max(1, len(map_xy) // 120_000)
    ax_map.scatter(
        map_xy[::stride, 0],
        map_xy[::stride, 1],
        s=0.10,
        c="#B8BEC6",
        alpha=0.38,
        linewidths=0,
        rasterized=True,
        label="Seq. 1 map",
    )
    ax_map.plot(
        map_path[:, 0],
        map_path[:, 1],
        color="#2563A6",
        linewidth=1.1,
        label=f"Seq. 1 keyframes (n={len(map_path)})",
        zorder=3,
    )
    ax_map.plot(
        query_truth[:, 0],
        query_truth[:, 1],
        color="#E07A2D",
        linewidth=1.1,
        linestyle=(0, (3.0, 1.4)),
        label=f"Seq. 2 queries (n={len(query_truth)})",
        zorder=4,
    )
    ax_map.scatter(
        [map_path[0, 0], query_truth[0, 0]],
        [map_path[0, 1], query_truth[0, 1]],
        s=16,
        marker="o",
        facecolor="white",
        edgecolor=["#2563A6", "#E07A2D"],
        linewidth=0.9,
        zorder=5,
    )
    ax_map.set_aspect("equal", adjustable="datalim")
    ax_map.set_xlabel("x (m)")
    ax_map.set_ylabel("y (m)")
    ax_map.grid(color="#D9DEE5", linewidth=0.4, alpha=0.65)
    ax_map.legend(
        loc="lower left",
        frameon=True,
        facecolor="white",
        edgecolor="#D4D8DE",
        framealpha=0.92,
        handlelength=2.1,
    )
    ax_map.text(
        0.0,
        1.02,
        "a",
        transform=ax_map.transAxes,
        fontsize=8,
        fontweight="bold",
        va="bottom",
    )

    # Panel b: hero metric. Multi-keyframe methods remain visibly separate.
    methods = [row["algorithm"] for row in summary]
    recalls = np.asarray(
        [
            [
                100.0 * float(row["recall_at_1"]),
                100.0 * float(row["recall_at_5"]),
                100.0 * float(row["recall_at_10"]),
            ]
            for row in summary
        ]
    )
    y = np.arange(len(methods), dtype=np.float64)
    bar_height = 0.22
    colors = ["#2563A6", "#40A6A6", "#AEB7C2"]
    labels = ["Recall@1", "Recall@5", "Recall@10"]
    for metric_index, (color, label) in enumerate(zip(colors, labels)):
        ax_bar.barh(
            y + (metric_index - 1) * bar_height,
            recalls[:, metric_index],
            height=bar_height * 0.90,
            color=color,
            edgecolor="none",
            label=label,
            zorder=3,
        )
    ax_bar.set_yticks(y, methods)
    ax_bar.invert_yaxis()
    ax_bar.set_xlim(0, 103)
    ax_bar.set_xlabel("Retrieval recall (%)")
    ax_bar.grid(axis="x", color="#D9DEE5", linewidth=0.45, zorder=0)
    ax_bar.spines[["top", "right"]].set_visible(False)
    proposed_index = methods.index("UpDown-SC")
    ax_bar.axhspan(
        proposed_index - 0.43,
        proposed_index + 0.43,
        color="#E8F1FA",
        zorder=-1,
    )
    ax_bar.get_yticklabels()[proposed_index].set_fontweight("bold")
    multi_start = next(
        (
            index
            for index, row in enumerate(summary)
            if "10_consecutive" in row["protocol"]
        ),
        len(methods),
    )
    if 0 < multi_start < len(methods):
        ax_bar.axhline(
            multi_start - 0.5,
            color="#707780",
            linewidth=0.7,
            linestyle=(0, (2.5, 2.0)),
        )
        ax_bar.text(
            102.5,
            (multi_start - 1) / 2,
            "single scan",
            rotation=90,
            va="center",
            ha="right",
            fontsize=6.2,
            color="#5E6670",
        )
        ax_bar.text(
            102.5,
            (multi_start + len(methods) - 1) / 2,
            "accumulated",
            rotation=90,
            va="center",
            ha="right",
            fontsize=6.2,
            color="#5E6670",
        )
    ax_bar.legend(
        loc="lower right",
        frameon=False,
        ncol=3,
        bbox_to_anchor=(1.0, 1.005),
        borderaxespad=0,
        columnspacing=1.2,
        handlelength=1.6,
    )
    ax_bar.text(
        0.0,
        1.02,
        "b",
        transform=ax_bar.transAxes,
        fontsize=8,
        fontweight="bold",
        va="bottom",
    )

    stem = output_dir / "construction_hall_cross_sequence"
    fig.savefig(stem.with_suffix(".svg"), bbox_inches="tight")
    fig.savefig(stem.with_suffix(".pdf"), bbox_inches="tight")
    fig.savefig(stem.with_suffix(".png"), dpi=300, bbox_inches="tight")
    fig.savefig(stem.with_suffix(".tiff"), dpi=600, bbox_inches="tight")
    plt.close(fig)

    qa = output_dir / "construction_hall_cross_sequence_qa.txt"
    qa.write_text(
        "\n".join(
            [
                "Core conclusion: UpDown-SC has the highest Recall@1 among "
                "single-scan methods under identical 2 m spatial keyframes.",
                "Archetype: asymmetric mixed-modality (trajectory context + recall bars).",
                "n definition: retain the first frame, then retain a frame when its "
                "3-D translation from the last retained frame is >= 2 m; no time/yaw trigger.",
                "Scope: experiment sampling only; production FAST-LIO keyframe logic unchanged.",
                "Test split: RTK-SLAM Construction Hall Seq. 1 database; Seq. 2 query.",
                "Metric: a retrieval is correct when any returned database keyframe is "
                "within 5 m of GNSS-aligned query truth.",
                "Variability: not applicable; deterministic descriptor retrieval, one run.",
                f"Missing data: no single-scan query excluded ({len(query_truth)}/"
                f"{len(query_truth)} have map overlap); "
                "Accumulated-input methods use the predeclared complete causal windows; "
                "STD uses 10 consecutive raw LiDAR scans.",
                "Baseline definition: native deskewed base_link clouds; only the proposed "
                "method applies its gravity-canonicalization module.",
                f"Source data: {root / 'results/recall_summary.csv'}",
                "Image integrity: map panel is a global XY projection with uniform point "
                "subsampling only; no local contrast or geometric manipulation.",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"Wrote figure bundle to {output_dir}")


if __name__ == "__main__":
    main()
